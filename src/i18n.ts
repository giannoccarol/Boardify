const dicts: Record<Locale, Record<DictKey, string>> = { en, it };

export function tr(locale: Locale, key: DictKey, vars?: Record<string, string | number>): string {
  let s: string = dicts[locale]?.[key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** t() bound to the locale stored in settings (English default). */
export function useT(): { t: (key: DictKey, vars?: Record<string, string | number>) => string; locale: Locale } {
  const locale = useBoardify((s) => s.settings.locale ?? "en");
  return { t: (key, vars) => tr(locale, key, vars), locale };
}
